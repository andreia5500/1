# -*- coding: utf-8 -*-
"""
Таблицы допусков.

1) IT14 (ГОСТ 25346) — для неуказанных отклонений диаметров: h14 / H14.
2) ГОСТ 30893.1-2002 (= ИСО 2768-1) — неуказанные предельные отклонения
   линейных и угловых размеров. Классы точности: f, m, c, v.
   По умолчанию берётся класс m (средний).
"""

# ---------------------------------------------------------------- IT14
# Ключ — верхняя граница интервала номинальных размеров, мм. Значение — IT14, мм.
IT14 = [
    (3,    0.25),
    (6,    0.30),
    (10,   0.36),
    (18,   0.43),
    (30,   0.52),
    (50,   0.62),
    (80,   0.74),
    (120,  0.87),
    (180,  1.00),
    (250,  1.15),
    (315,  1.30),
    (400,  1.40),
    (500,  1.55),
]


def it14(nominal):
    """IT14 в мм для номинального размера."""
    n = abs(float(nominal))
    for hi, v in IT14:
        if n <= hi + 1e-9:
            return v
    raise ValueError('Таблица IT14 в этой программе ограничена 500 мм.')


# ------------------------------------------- ГОСТ 30893.1, линейные размеры
# (верхняя граница интервала, {класс: ±отклонение, мм})
# None означает, что для этого интервала класс не нормируется.
GOST_LINEAR = [
    (3,    {'f': 0.05, 'm': 0.10, 'c': 0.20, 'v': None}),
    (6,    {'f': 0.05, 'm': 0.10, 'c': 0.30, 'v': 0.50}),
    (30,   {'f': 0.10, 'm': 0.20, 'c': 0.50, 'v': 1.00}),
    (120,  {'f': 0.15, 'm': 0.30, 'c': 0.80, 'v': 1.50}),
    (400,  {'f': 0.20, 'm': 0.50, 'c': 1.20, 'v': 2.50}),
    (1000, {'f': 0.30, 'm': 0.80, 'c': 2.00, 'v': 4.00}),
    (2000, {'f': 0.50, 'm': 1.20, 'c': 3.00, 'v': 6.00}),
    (4000, {'f': None, 'm': 2.00, 'c': 4.00, 'v': 8.00}),
]

# Размеры менее 0,5 мм по ГОСТ 30893.1 не нормируются — отклонения указывают
# непосредственно у размера.
GOST_LINEAR_MIN = 0.5

# ------------------------------- ГОСТ 30893.1, радиусы скругления и фаски
GOST_CHAMFER = [
    (3,    {'f': 0.2, 'm': 0.2, 'c': 0.4, 'v': 0.4}),
    (6,    {'f': 0.5, 'm': 0.5, 'c': 1.0, 'v': 1.0}),
    (1e12, {'f': 1.0, 'm': 1.0, 'c': 2.0, 'v': 2.0}),
]

# --------------------------------------------- ГОСТ 30893.1, угловые размеры
# Интервал — по длине более короткой стороны угла, мм. Отклонение в градусах.
GOST_ANGULAR = [
    (10,   {'f': 1.0,      'm': 1.0,      'c': 1.5,      'v': 3.0}),
    (50,   {'f': 0.5,      'm': 0.5,      'c': 1.0,      'v': 2.0}),
    (120,  {'f': 20 / 60., 'm': 20 / 60., 'c': 0.5,      'v': 1.0}),
    (400,  {'f': 10 / 60., 'm': 10 / 60., 'c': 15 / 60., 'v': 0.5}),
    (1e12, {'f': 5 / 60.,  'm': 5 / 60.,  'c': 10 / 60., 'v': 20 / 60.}),
]


def _lookup(table, size, cls):
    s = abs(float(size))
    for hi, row in table:
        if s <= hi + 1e-9:
            return row.get(cls)
    return None


def gost_linear(nominal, cls='m'):
    """Симметричное отклонение ± для линейного размера, мм. None — не нормируется."""
    if abs(float(nominal)) < GOST_LINEAR_MIN:
        return None
    return _lookup(GOST_LINEAR, nominal, cls)


def gost_chamfer(nominal, cls='m'):
    """Симметричное отклонение ± для фаски / радиуса скругления, мм."""
    if abs(float(nominal)) < GOST_LINEAR_MIN:
        return None
    return _lookup(GOST_CHAMFER, nominal, cls)


def gost_angular(short_side_mm, cls='m'):
    """Симметричное отклонение ± для угла, в градусах."""
    return _lookup(GOST_ANGULAR, short_side_mm, cls)


# --------------------------------------------------------------- h14 / H14
def h14_shaft(diameter):
    """Вал h14: (верхнее, нижнее) в мм."""
    return 0.0, -it14(diameter)


def H14_hole(diameter):
    """Отверстие H14: (верхнее, нижнее) в мм."""
    return +it14(diameter), 0.0


def js14(nominal):
    """js14 / JS14 — симметрично ±IT14/2."""
    t = it14(nominal) / 2.0
    return +t, -t


# ------------------------------------------------------------ форматирование
def fmt_num(v, decimals=None, comma=True):
    """Число в текст без хвостовых нулей. decimals — принудительная разрядность."""
    if v is None:
        return ''
    if decimals is None:
        s = ('%.4f' % v).rstrip('0').rstrip('.')
        if s in ('', '-'):
            s = '0'
    else:
        s = ('%.*f' % (decimals, v))
    if comma:
        s = s.replace('.', ',')
    return s


# Разделитель для случая "два плюса" или "два минуса" в отклонении
# (напр. верхнее +0,1, нижнее +0,05 — оба одного знака): по прямому
# указанию пользователя пишется НЕ через слэш ("+0,1/+0,05"), а как на
# чертеже — верхнее значение над нижним, в той же ячейке.
#
# РЕШЕНО живым тестом (пользователь сам ввёл в КОМПАСе пример "ф27" с
# "-0,1" сверху и "-0,2" снизу через кнопку "Индекс" -> "Средней высоты"
# и сохранил; прочитано через API7 Stamp.Text(...).Str):
#   raw = "⌀" + "27" + "$m" + "-0,1" + ";" + "-0,2" + "$"
# т.е. это ТОТ ЖЕ спецкод "индекс средней высоты", что уже используется
# для одиночного отклонения (kompas_dims.INDEX_MID_START/END = "$m"/";$"),
# только внутри одной пары "$m...$" два значения через ";": верхнее —
# до ";", нижнее — после. Для одиночного отклонения нижняя часть после
# ";" просто пустая, поэтому старый формат "$m<dev>;$" остаётся частным
# случаем этого же правила.
#
# Здесь, в tolerances.fmt_dev, для ЛЮБОЙ пары несимметричных отклонений
# (оба одного знака, напр. "два плюса"/"два минуса", И РАВНО ТАК ЖЕ два
# РАЗНЫХ знака, напр. "+0,3 -0,5") возвращается "<верхнее>;<нижнее>"
# (разделитель — точка с запятой); обёртку в спецкоды "$m...$" делает
# kompas_dims._maybe_index_dev, которая по наличию ";" в строке отличает
# этот случай от одиночного отклонения. По прямому указанию пользователя
# ("если допуски например +0,3 -0,5 их тоже нужно по индексам, а не через
# слеш") слэш ("+0,62/-0,1") для разных знаков БОЛЬШЕ НЕ используется —
# раньше это было единственным оставшимся случаем со слэшем, теперь и он
# уходит на индекс средней высоты, как и одинаковые знаки.
DEV_STACK_SEP = ';'


def fmt_dev(hi, lo, comma=True):
    """
    Отклонения в компактный текст:
      (+0.02, -0.02) -> ±0,02
      (0, -0.52)     -> -0,52
      (+0.43, 0)     -> +0,43
      (+0.62, +0.1)  -> "+0,62;+0,1" (два плюса - индекс средней высоты
                        над/под, см. DEV_STACK_SEP и kompas_dims._maybe_index_dev)
      (-0.1, -0.3)   -> "-0,1;-0,3" (два минуса - аналогично)
      (+0.3, -0.5)   -> "+0,3;-0,5" (разные знаки - ТОЖЕ индекс средней
                        высоты, не слэш - по прямому указанию пользователя)
    """
    if hi is None and lo is None:
        return ''
    hi = 0.0 if hi is None else float(hi)
    lo = 0.0 if lo is None else float(lo)

    if abs(hi + lo) < 1e-9 and abs(hi) > 1e-9:
        return '±' + fmt_num(abs(hi), comma=comma)
    if abs(lo) < 1e-9 and abs(hi) > 1e-9:
        return '+' + fmt_num(hi, comma=comma)
    if abs(hi) < 1e-9 and abs(lo) > 1e-9:
        return fmt_num(lo, comma=comma)          # знак минуса уже в числе
    if abs(hi) < 1e-9 and abs(lo) < 1e-9:
        return ''
    a = ('+' if hi > 0 else '') + fmt_num(hi, comma=comma)
    b = ('+' if lo > 0 else '') + fmt_num(lo, comma=comma)
    # несимметричная пара (оба значения ненулевые, не "±") - всегда через
    # индекс средней высоты (DEV_STACK_SEP), независимо от того, одного
    # знака оба значения или разных - см. примечание у DEV_STACK_SEP выше.
    return a + DEV_STACK_SEP + b


def fmt_angle_dev(deg, comma=True):
    """Угловое отклонение в градусах -> ±1° / ±30' / ±1°30'."""
    if deg is None:
        return ''
    d = int(abs(deg))
    m = int(round((abs(deg) - d) * 60))
    if m == 60:
        d, m = d + 1, 0
    if d and m:
        return "±%d°%d'" % (d, m)
    if d:
        return '±%d°' % d
    return "±%d'" % m


def fmt_angle_pair(hi, lo):
    if hi is None and lo is None:
        return ''
    hi, lo = hi or 0.0, lo or 0.0
    if abs(hi + lo) < 1e-9:
        return fmt_angle_dev(hi) if hi else ''
    def one(v):
        return ('+' if v > 0 else '-') + fmt_angle_dev(abs(v))[1:] if v else ''
    return one(hi) + (';' + one(lo) if hi and lo else one(lo))
